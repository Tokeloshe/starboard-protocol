# Mechanically transcribes conformance/registry_fixtures.hpp (the C++
# fixtures generated from Python + libsodium) into a C99 header, so the C
# port is tested against the very same bytes as conformance/runner.cpp.
# No data is re-derived here: only the C++ syntax is rewritten.
#
#   Usage: python3 gen_c_fixtures.py ../../../conformance/registry_fixtures.hpp \
#              > registry_fixtures_c.h
#   (The Makefile regenerates it on every build.)

import re
import sys

NAMES = ["REG_PUB", "NOW_MS", "ENTRIES", "REVOKED_IDS", "SNAPSHOT_EPOCH_MS",
         "SNAPSHOT", "PROOFS", "ASSERT_OK", "ASSERT_REVOKED",
         "ASSERT_EXPIRED", "ASSERT_LONG"]


def main(path):
    src = open(path, encoding="utf-8").read()
    start = src.index("namespace fixtures {") + len("namespace fixtures {")
    end = src.rindex("} // namespace fixtures")
    body = src[start:end]

    def oid(m):
        s = m.group(1).upper()
        if len(s) > 12 or not re.fullmatch(r"[A-Z0-9-]*", s):
            raise SystemExit("unexpected object id: %r" % s)
        return "{ \"%s\" }" % s

    body = re.sub(r'starboard::make_object_id\("([^"]*)"\)', oid, body)
    body = re.sub(r"static_cast<starboard::Tier>\((\d+)\)", r"(Tier)\1", body)
    body = body.replace("starboard::registry::", "")
    body = body.replace("starboard::", "")
    body = body.replace("inline const", "static const")
    for n in NAMES:
        body = re.sub(r"\b%s\b" % n, "FX_" + n, body)
    if "starboard" in body or "::" in body or "inline" in body:
        raise SystemExit("untranslated C++ syntax remains")

    out = sys.stdout
    out.write("/* GENERATED by ports/c/tests/gen_c_fixtures.py from\n"
              "   conformance/registry_fixtures.hpp. Do not edit. */\n")
    out.write("#ifndef SB_REGISTRY_FIXTURES_C_H\n#define SB_REGISTRY_FIXTURES_C_H\n")
    out.write("#include \"starboard_registry.h\"\n")
    out.write(body)
    out.write("#endif /* SB_REGISTRY_FIXTURES_C_H */\n")


if __name__ == "__main__":
    main(sys.argv[1])
