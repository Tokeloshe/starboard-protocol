# Writes SYNTHETIC but standards-shaped CCSDS 508.0-B-1 KVN conjunction data
# messages to examples/cdm/. Geometry is built directly AT TCA (where real
# CDMs give it): object 2 sits at object 1's position plus a miss vector
# perpendicular to the relative velocity. No real object, operator or
# provider is represented; designators use the 2026-9xx block and the
# originator is "STARBOARD-EXAMPLE".
#
#   python3 tools/make_example_cdms.py            # (re)write examples/cdm/
import math
import os

MU = 3.986004418e14
RE = 6378137.0
OMEGA = 7.292115e-5
OUT = os.path.join(os.path.dirname(__file__), "..", "examples", "cdm")


def unit(v):
    n = math.sqrt(sum(x * x for x in v))
    return [x / n for x in v]


def cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0]]


def add(a, b, s=1.0):
    return [x + s * y for x, y in zip(a, b)]


def circular(alt_km, incl_deg, raan_deg, u_deg):
    r = RE + alt_km * 1e3
    v = math.sqrt(MU / r)
    i, O, u = (math.radians(x) for x in (incl_deg, raan_deg, u_deg))
    pos = [r * (math.cos(O) * math.cos(u) - math.sin(O) * math.sin(u) * math.cos(i)),
           r * (math.sin(O) * math.cos(u) + math.cos(O) * math.sin(u) * math.cos(i)),
           r * math.sin(u) * math.sin(i)]
    vel = [v * (-math.cos(O) * math.sin(u) - math.sin(O) * math.cos(u) * math.cos(i)),
           v * (-math.sin(O) * math.sin(u) + math.cos(O) * math.cos(u) * math.cos(i)),
           v * math.cos(u) * math.sin(i)]
    return pos, vel


def encounter(p1, v1, v2, miss_m, miss_dir_hint):
    """Object 2 at TCA: p1 + miss, miss perpendicular to v_rel."""
    dv = unit(add(v2, v1, -1.0))
    m = add(miss_dir_hint, dv, -sum(a * b for a, b in zip(miss_dir_hint, dv)))
    m = unit(m)
    return add(p1, m, miss_m)


def obj_block(n, desig, name, intl, otype, man, frame, pos, vel, cov):
    s = [f"OBJECT                   = OBJECT{n}",
         f"OBJECT_DESIGNATOR        = {desig}",
         "CATALOG_NAME             = SATCAT",
         f"OBJECT_NAME              = {name}",
         f"INTERNATIONAL_DESIGNATOR = {intl}",
         f"OBJECT_TYPE              = {otype}",
         "OPERATOR_ORGANIZATION    = EXAMPLE",
         "EPHEMERIS_NAME           = NONE",
         "COVARIANCE_METHOD        = CALCULATED",
         f"MANEUVERABLE             = {man}",
         f"REF_FRAME                = {frame}",
         "GRAVITY_MODEL            = EGM-96: 36D 36O",
         "ATMOSPHERIC_MODEL        = JACCHIA 70 DCA",
         "N_BODY_PERTURBATIONS     = MOON, SUN",
         "SOLAR_RAD_PRESSURE       = YES",
         "EARTH_TIDES              = YES",
         "INTRACK_THRUST           = NO"]
    for k, x in zip(("X", "Y", "Z"), pos):
        s.append(f"{k:<25}= {x / 1e3:.6f} [km]")
    for k, x in zip(("X_DOT", "Y_DOT", "Z_DOT"), vel):
        s.append(f"{k:<25}= {x / 1e3:.9f} [km/s]")
    for k, x in zip(("CR_R", "CT_R", "CT_T", "CN_R", "CN_T", "CN_N"), cov):
        s.append(f"{k:<25}= {x:.4E} [m**2]")
    # Velocity covariance rows (present in real CDMs; ignored by the binding).
    for k in ("CRDOT_R", "CRDOT_T", "CRDOT_N", "CRDOT_RDOT"):
        s.append(f"{k:<25}= 0.0000E+00 [m**2/s]" if k != "CRDOT_RDOT"
                 else f"{k:<25}= 1.0000E-04 [m**2/s**2]")
    return s


def write(fname, msg_id, tca, miss, pc, comment, o1, o2):
    rel_speed = math.sqrt(sum((a - b) ** 2 for a, b in zip(o1["vel"], o2["vel"])))
    lines = ["CCSDS_CDM_VERS           = 1.0",
             f"COMMENT {comment}",
             "COMMENT SYNTHETIC EXAMPLE generated by tools/make_example_cdms.py",
             "CREATION_DATE            = 2026-10-24T12:00:00.000",
             "ORIGINATOR               = STARBOARD-EXAMPLE",
             "MESSAGE_FOR              = EXAMPLE",
             f"MESSAGE_ID               = {msg_id}",
             f"TCA                      = {tca}",
             f"MISS_DISTANCE            = {miss:.1f} [m]",
             f"RELATIVE_SPEED           = {rel_speed:.1f} [m/s]",
             "COMMENT COLLISION_PROBABILITY omitted: Starboard computes its own"]
    lines += obj_block(1, **o1)
    lines += obj_block(2, **o2)
    path = os.path.join(OUT, fname)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(path))


def main():
    os.makedirs(OUT, exist_ok=True)

    # 1. The README demo crossing: two operational payloads, 45 deg crossing,
    #    150 m radial miss at 552 km.
    p1, v1 = circular(551.863, 0.0, 0.0, 0.0)
    _, v2 = circular(552.013, 45.0, 0.0, 0.0)
    p2 = encounter(p1, v1, v2, 150.0, unit(p1))
    write("crossing_demo.cdm", "SB-EX-0001", "2026-11-02T03:14:15.926",
          150.0, "1.043E-03", "two rival operators, 45 deg crossing",
          dict(desig="99001", name="ACME-1", intl="2026-901A", otype="PAYLOAD",
               man="YES", frame="EME2000", pos=p1, vel=v1,
               cov=(4.0e2, -1.2e2, 9.0e4, 1.0e1, -3.0e1, 2.5e3)),
          dict(desig="99002", name="ORBX-9", intl="2026-902B", otype="PAYLOAD",
               man="YES", frame="EME2000", pos=p2, vel=v2,
               cov=(6.4e2, -2.0e2, 1.2e5, 1.5e1, -4.0e1, 3.6e3)))

    # 2. Constellation-shell payload vs tumbling debris, near head-on, with
    #    the along-track-elongated covariance typical of LEO tracking.
    p1, v1 = circular(550.0, 53.0, 120.0, 37.0)
    _, v2 = circular(549.6, 97.6, 300.0, 143.0)
    v2 = [-x for x in v1]
    v2 = add(v2, unit(cross(p1, v1)), 2400.0)
    v2 = [x * math.sqrt(MU / (RE + 549.6e3)) / math.sqrt(sum(y * y for y in v2))
          for x in v2]
    p2 = encounter(p1, v1, v2, 312.0, unit(cross(p1, v1)))
    write("shell_vs_debris.cdm", "SB-EX-0002", "2026-11-05T21:07:44.500",
          312.0, "2.2E-04", "constellation payload vs untracked-attitude debris",
          dict(desig="99010", name="SHELL-1042", intl="2026-910C",
               otype="PAYLOAD", man="YES", frame="GCRF", pos=p1, vel=v1,
               cov=(2.5e3, 1.8e3, 4.0e5, -6.0e1, 1.1e2, 1.6e3)),
          dict(desig="99011", name="DEB-FRAGMENT", intl="2026-911ABC",
               otype="DEBRIS", man="N/A", frame="GCRF", pos=p2, vel=v2,
               cov=(1.0e4, -4.0e3, 2.5e6, 2.0e2, -3.0e2, 6.4e3)))

    # 3. The same kind of message in an Earth-fixed frame (ITRF), as several
    #    providers publish: inertial -> ITRF at the TCA instant (frozen Earth,
    #    the inverse of the binding's mapping), so the binding recovers it.
    p1, v1 = circular(780.0, 86.4, 45.0, 210.0)
    _, v2 = circular(780.2, 98.5, 160.0, 205.0)
    p2 = encounter(p1, v1, v2, 95.0, unit(p1))

    def to_itrf(p, v):
        return p, [v[0] + OMEGA * p[1], v[1] - OMEGA * p[0], v[2]]
    q1, w1 = to_itrf(p1, v1)
    q2, w2 = to_itrf(p2, v2)
    write("itrf_rocket_body.cdm", "SB-EX-0003", "2026-312T08:45:00.000",
          95.0, "6.8E-03", "operational payload vs spent upper stage (ITRF)",
          dict(desig="99020", name="POLAR-7", intl="2026-920A",
               otype="PAYLOAD", man="YES", frame="ITRF", pos=q1, vel=w1,
               cov=(9.0e2, 3.0e2, 1.0e5, 1.0e1, 2.0e1, 4.0e2)),
          dict(desig="99021", name="R/B", intl="2026-921B",
               otype="ROCKET BODY", man="NO", frame="ITRF", pos=q2, vel=w2,
               cov=(4.0e3, 1.0e3, 9.0e5, 5.0e1, -5.0e1, 2.0e3)))


if __name__ == "__main__":
    main()
