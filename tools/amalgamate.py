# Starboard Protocol — single-file distribution generator.
#
# Concatenates the C99 flight library (ports/c) into two files, the way
# SQLite ships:
#
#   dist/starboard.h   every public header, in dependency order
#   dist/starboard.c   every library source, with local #includes removed
#
# Drop both into any C or C++ project and compile starboard.c with
# -std=c99 -ffp-contract=off. Nothing else is needed (libm only).
# The output is generated: edit ports/c and re-run this script.
#
#   python3 tools/amalgamate.py            # writes dist/
#   python3 tools/amalgamate.py --check    # fails if dist/ is out of date
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "ports" / "c"
OUT = ROOT / "dist"

HEADERS = ["starboard.h", "starboard_cdm.h", "starboard_flock.h",
           "starboard_registry.h", "starboard_fsw.h", "starboard_easy.h"]
SOURCES = ["canon.c", "geometry.c", "propagator.c", "covariance.c",
           "screening.c", "rules.c", "maneuver.c", "multibody.c",
           "broadphase.c", "sha512.c", "registry.c", "ed25519.c", "cdm.c",
           "fsw.c", "ccsds.c", "flock.c", "softdouble.c", "easy.c"]

LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')


def version() -> str:
    text = (SRC / "starboard_fsw.h").read_text()
    m = re.search(r"SB_FSW_VERSION\s+\(0x([0-9A-Fa-f]{8})U\)", text)
    v = int(m.group(1), 16)
    return f"{(v >> 24) & 0xFF}.{(v >> 16) & 0xFF}.{(v >> 8) & 0xFF}"


def strip_local(name: str) -> str:
    lines = []
    for line in (SRC / name).read_text().splitlines():
        m = LOCAL_INCLUDE.match(line)
        if m:
            lines.append(f"/* #include \"{m.group(1)}\" (amalgamated) */")
        else:
            lines.append(line)
    return "\n".join(lines) + "\n"


BANNER = """/*
 * Starboard Protocol {ver} — single-file C99 library (amalgamation).
 * SPDX-License-Identifier: AGPL-3.0-or-later   (commercial: COMMERCIAL-LICENSE.md)
 * Copyright (C) 2026 James H.  https://github.com/Tokeloshe/starboard-protocol
 *
 * GENERATED by tools/amalgamate.py from ports/c — do not edit by hand.
 *
 * Build:   cc -std=c99 -O2 -ffp-contract=off -c starboard.c
 *          (-ffp-contract=off is REQUIRED: it keeps every satellite's
 *           arithmetic bit-identical. The built-in self-test refuses to
 *           run on a build that gets this wrong.)
 * Start:   see starboard_easy.h section below, or docs/QUICKSTART.md.
 */
"""


def build() -> dict:
    ver = version()
    h = [BANNER.format(ver=ver), "#ifndef STARBOARD_AMALGAMATION_H\n"
         "#define STARBOARD_AMALGAMATION_H\n"]
    for name in HEADERS:
        h.append(f"\n/* ==== {name} ==== */\n")
        h.append(strip_local(name))
    h.append("\n#endif /* STARBOARD_AMALGAMATION_H */\n")

    c = [BANNER.format(ver=ver), '#include "starboard.h"\n']
    for name in SOURCES:
        c.append(f"\n/* ==== {name} ==== */\n")
        c.append(strip_local(name))
    return {"starboard.h": "".join(h), "starboard.c": "".join(c)}


def main() -> int:
    files = build()
    if "--check" in sys.argv:
        stale = [n for n, t in files.items()
                 if not (OUT / n).exists() or (OUT / n).read_text() != t]
        if stale:
            print("dist/ is out of date: run python3 tools/amalgamate.py",
                  file=sys.stderr)
            return 1
        print("dist/ is up to date")
        return 0
    OUT.mkdir(exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
        print(f"wrote dist/{name} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
